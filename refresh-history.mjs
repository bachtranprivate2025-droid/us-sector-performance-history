export const PAGE_SIZE = 6;
export function buildHistoryPoints(history, start, end, mode) {
    const first = history.dates.findIndex((date) => date >= start && date <= end);
    if (first === -1)
        return [];
    const base = history.dates[first - 1] ?? history.baseline;
    return history.dates.slice(first).filter((date) => date <= end).map((date, offset) => {
        const previous = mode === "daily" ? history.dates[first + offset - 1] ?? history.baseline : base;
        const point = { date };
        for (const [ticker, series] of Object.entries(history.prices)) {
            const price = series[date];
            const anchor = previous ? series[previous] : undefined;
            point[ticker] = price > 0 && anchor && anchor > 0 ? (price / anchor - 1) * 100 : null;
        }
        return point;
    });
}
export function monthsBefore(day, months) {
    const [year, month, date] = day.split("-").map(Number);
    const monthStart = new Date(Date.UTC(year, month - 1 - months, 1));
    const lastDay = new Date(Date.UTC(monthStart.getUTCFullYear(), monthStart.getUTCMonth() + 1, 0)).getUTCDate();
    monthStart.setUTCDate(Math.min(date, lastDay));
    return monthStart.toISOString().slice(0, 10);
}
const exchangeDate = new Intl.DateTimeFormat("en-CA", {
    timeZone: "America/New_York", year: "numeric", month: "2-digit", day: "2-digit",
});
const cache = new Map();
async function readFeed(ticker) {
    const url = new URL(`https://query1.finance.yahoo.com/v8/finance/chart/${encodeURIComponent(ticker)}`);
    url.search = "range=2y&interval=1d&includePrePost=false";
    const response = await fetch(url, {
        headers: { "User-Agent": "Mozilla/5.0 SectorPerformanceHistory/1.0", Accept: "application/json" },
        cache: "no-store", signal: AbortSignal.timeout(9_000),
    });
    if (!response.ok)
        throw new Error(`${ticker}: HTTP ${response.status}`);
    const json = await response.json();
    const result = json.chart?.result?.[0];
    const adjusted = result?.indicators?.adjclose?.[0]?.adjclose;
    const now = Date.now();
    const today = exchangeDate.format(now);
    const close = (result?.meta?.currentTradingPeriod?.regular?.end ?? 0) * 1000;
    const todayClosed = close > 0 && exchangeDate.format(close) === today && now >= close + 15 * 60_000;
    const feed = {};
    for (const [index, timestamp] of (result?.timestamp ?? []).entries()) {
        const date = exchangeDate.format(timestamp * 1000);
        const price = adjusted?.[index];
        if (date > today || (date === today && !todayClosed))
            continue;
        if (typeof price === "number" && Number.isFinite(price) && price > 0)
            feed[date] = price;
    }
    if (!Object.keys(feed).length)
        throw new Error(`${ticker}: no adjusted prices`);
    return feed;
}
function loadFeed(ticker) {
    const entry = cache.get(ticker);
    if (entry && entry.expires > Date.now())
        return entry.promise;
    const promise = readFeed(ticker).catch((error) => {
        if (cache.get(ticker)?.promise === promise)
            cache.delete(ticker);
        throw error;
    });
    cache.set(ticker, { expires: Date.now() + 300_000, promise });
    return promise;
}
export async function GET(request) {
    const url = new URL(request.url);
    const kind = url.searchParams.get("kind");
    const page = Number(url.searchParams.get("page") ?? "0");
    const universe = kind === "main" ? MAIN : kind === "sub" ? SUB : null;
    if (!universe || !Number.isInteger(page) || page < 0 || page * PAGE_SIZE >= universe.length) {
        return Response.json({ error: "Nhóm ETF không hợp lệ." }, { status: 400 });
    }
    const tickers = ["SPY", ...universe.slice(page * PAGE_SIZE, (page + 1) * PAGE_SIZE).map(({ ticker }) => ticker)];
    const [benchmark, ...others] = await Promise.allSettled(tickers.map(loadFeed));
    if (benchmark.status === "rejected") {
        return Response.json({ error: "Chưa tải được lịch phiên SPY từ Yahoo Finance." }, { status: 502 });
    }
    const fullDates = Object.keys(benchmark.value).sort();
    const cutoff = monthsBefore(exchangeDate.format(Date.now()), 12);
    const dates = fullDates.filter((date) => date >= cutoff);
    const baseline = fullDates.filter((date) => date < cutoff).at(-1) ?? null;
    const payload = { dates, baseline, prices: { SPY: benchmark.value }, missing: [] };
    others.forEach((result, index) => {
        const ticker = tickers[index + 1];
        if (result.status === "fulfilled")
            payload.prices[ticker] = result.value;
        else
            payload.missing.push(ticker);
    });
    for (const [ticker, feed] of Object.entries(payload.prices)) {
        payload.prices[ticker] = Object.fromEntries(Object.entries(feed).filter(([date]) => date >= cutoff || date === baseline));
    }
    return Response.json(payload, { headers: { "Cache-Control": "no-store" } });
}
import { writeFile, rename } from "node:fs/promises";
const groups = {};
for (const [kind, universe] of Object.entries({ main: MAIN, sub: SUB })) {
    for (let page = 0; page < Math.ceil(universe.length / PAGE_SIZE); page++) {
        const response = await GET(new Request(`https://localhost/?kind=${kind}&page=${page}`));
        const data = await response.json();
        if (!response.ok || !data.dates?.length || data.missing?.length) {
            throw new Error(`${kind}-${page}: ${data.error ?? `missing ${data.missing?.join(", ")}`}`);
        }
        groups[`${kind}/${page}`] = data;
    }
}
const path = process.argv[2] ?? "history-data.js";
await writeFile(`${path}.tmp`, `window.sectorHistory = ${JSON.stringify(groups)};\n`, "utf8");
await rename(`${path}.tmp`, path);
